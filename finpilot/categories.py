def by_mcc(mcc: str) -> str | None:
    try:
        code = int(str(mcc).strip())
    except ValueError:
        return None
    for codes, cat in MCC_RULES:
        if code in codes:
            return cat
    return None


def _norm(s: str) -> str:
    return str(s).lower().replace("ё", "е")


def by_keywords(text: str) -> str | None:
    t = f" {_norm(text)} "
    for cat, words in KEYWORDS.items():
        if any(_norm(w) in t for w in words):
            return cat
    return None


def categorize(df: pd.DataFrame) -> pd.Series:
    def one(row) -> str:
        if row.amount > 0:
            return "Поступления"
        return (BANK_CATEGORY_MAP.get(row.bank_category)
                or by_mcc(row.mcc)
                or by_keywords(row.description)
                or "Прочее")
    return df.apply(one, axis=1)
